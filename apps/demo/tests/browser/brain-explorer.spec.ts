import { expect, test } from '@playwright/test'
const ready = async (page: import('@playwright/test').Page) => { await page.goto('/'); await expect(page.locator('.brain-explorer')).toHaveAttribute('data-ready', 'true') }
test('search, selection, relationship navigation and renderer switches share identities', async ({ page }) => {
  await ready(page)
  await page.getByRole('textbox', { name: 'Search loaded context', exact: true }).fill('review composer')
  await page.getByRole('button', { name: /Review composer skill/ }).click()
  await expect(page.getByRole('heading', { name: 'Review composer' })).toBeVisible()
  await page.getByRole('tab', { name: /Relationships/ }).click()
  await page.getByRole('button', { name: /Declares context · directed Brand voice/ }).click()
  await expect(page.locator('.brain-focused-edge')).toContainText('Review composer → Brand voice')
  await page.getByLabel('Renderer', { exact: true }).selectOption('svg')
  await expect(page.locator('.brain-viewport')).toHaveAttribute('data-active-renderer', 'svg')
  await expect(page.getByRole('heading', { name: 'Brand voice', exact: true })).toBeVisible()
  await page.getByLabel('Renderer', { exact: true }).selectOption('list')
  await expect(page.locator('.brain-viewport')).toHaveAttribute('data-active-renderer', 'list')
  await page.getByRole('button', { name: /^Voice & tone Page/ }).click()
  await expect(page.getByRole('heading', { name: 'Voice & tone' })).toBeVisible()
})
test('drag threshold, discrete rotation, fit, reset and blank-space clearing', async ({ page }) => {
  await ready(page)
  await page.getByLabel('Renderer', { exact: true }).selectOption('svg')
  const before = await page.locator('.brain-svg-renderer > g').getAttribute('transform')
  await page.getByRole('button', { name: 'Rotate left', exact: true }).click()
  await expect(page.locator('.brain-svg-renderer > g')).not.toHaveAttribute('transform', before!)
  const selected = page.locator('.brain-svg-node').filter({ has: page.locator('text', { hasText: /^Brand voice$/ }) })
  const bounds = await selected.boundingBox()
  expect(bounds).toBeTruthy()
  await page.mouse.move(bounds!.x + bounds!.width / 2, bounds!.y + bounds!.height / 2)
  await page.mouse.down(); await page.mouse.move(bounds!.x + 85, bounds!.y + 70, { steps: 8 }); await page.mouse.up()
  await expect(page.getByRole('heading', { name: 'Brand voice', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Fit visible context' }).click()
  await page.getByRole('button', { name: 'Reset camera' }).click()
  await page.locator('.brain-svg-renderer').click({ position: { x: 25, y: 125 } })
  await expect(page.getByRole('complementary', { name: 'Node inspector' })).toHaveCount(0)
})
