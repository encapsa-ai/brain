test('navigation and typing pause auto-rotation until explicitly resumed', async ({ page }) => {
  await ready(page)
  const toggle = page.getByRole('button', { name: 'Auto-rotate', exact: true })
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Hide context navigator', exact: true }).click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('textbox', { name: 'Search loaded context', exact: true }).focus()
  await page.keyboard.press('r')
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await page.keyboard.press('Escape')
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
})
